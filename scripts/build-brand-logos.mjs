// Generates src/data/brand-logos.ts from the Simple Icons package (CC0 icon data).
// Brand marks remain trademarks of their owners; they are shown only to identify
// the makes the dealership sells. Run: node scripts/build-brand-logos.mjs
import { createRequire } from "node:module";
import { writeFileSync } from "node:fs";

const si = createRequire(import.meta.url)("simple-icons");
const norm = (s) => s.normalize("NFKD").toLowerCase().replace(/[^a-z]/g, "");
const icons = Object.values(si).filter((x) => x && x.title && x.path);

/** Brand name as used in the site → Simple Icons title, when they differ. */
const aliases = { "Mercedes-Benz": "Mercedes", Skoda: "Škoda" };
const { brandDirectory } = await import("../src/data/brand-list.ts");

const out = {};
for (const brand of brandDirectory) {
  const want = norm(aliases[brand] ?? brand);
  const hit = icons.find((i) => norm(i.title) === want);
  if (hit) out[brand] = hit.path;
}
const body = `// Generated by scripts/build-brand-logos.mjs from Simple Icons (CC0). Do not edit by hand.
// Logos are trademarks of their respective owners, used to identify the makes offered.
export const brandLogos: Record<string, string> = ${JSON.stringify(out, null, 2)};
`;
writeFileSync(new URL("../src/data/brand-logos.ts", import.meta.url), body);
console.log(`${Object.keys(out).length}/${brandDirectory.length} logos:`, Object.keys(out).join(", "));
